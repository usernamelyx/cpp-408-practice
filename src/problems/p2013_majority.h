// 题目：
//   已知一个整数序列 A = (a0, a1, ..., an-1)，其中 0 <= ai < n。
//   若存在 ap1 = ap2 = ... = apm = x 且 m > n/2 (0 <= pk < n, 1 <= k <= m)，
//   则称 x 为 A 的主元素。
//   例如 A = (0, 5, 5, 3, 5, 7, 5, 5)，则 5 为主元素；
//   又如 A = (0, 5, 5, 3, 5, 1, 5, 7)，则 A 中没有主元素。
//   假设 A 中的 n 个元素保存在一个一维数组中，
//   请设计一个尽可能高效的算法，找出 A 的主元素。
//   若存在主元素，则输出该元素；否则输出 -1。
//
// 要求：
//   时间复杂度 O(n)，空间复杂度 O(1)
//
// 思路（摩尔投票法 / Boyer-Moore Majority Vote）：
//   主元素出现次数超过一半，那么把它和任意其他元素"两两相消"，
//   最后剩下的一定是主元素（若存在）。
//   第一遍扫描求候选者，第二遍扫描验证候选者是否真的超过一半。
// =============================================================

// 返回主元素；不存在则返回 -1
